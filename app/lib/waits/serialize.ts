import type { WaitRow } from './sweeper';
import type { ResolvedOwner } from './owner';

/** The public shape of a wait. Dates are ISO strings; BigInt never leaves the server. */
export function serializeWait(w: WaitRow, owner?: ResolvedOwner | null) {
  return {
    id: w.id,
    kind: w.kind,
    template_key: w.template_key,
    step: w.step,
    title: w.title,
    detail: w.detail,
    state: w.state,
    owner_function_id: w.owner_function_id,
    owner_user_id: w.owner_user_id,
    owner_contact_id: w.owner_contact_id,
    stand_in_user_id: w.stand_in_user_id,
    escalated_to_user_id: w.escalated_to_user_id,
    resolved_owner: owner ? { user_id: owner.user_id, source: owner.source, role_key: owner.role_key } : null,
    client_id: w.client_id,
    accord_id: w.accord_id,
    project_id: w.project_id,
    charter_id: w.charter_id,
    site_id: w.site_id,
    task_id: w.task_id,
    arc_id: w.arc_id,
    approval_request_id: w.approval_request_id,
    email_thread_id: w.email_thread_id,
    started_at: w.started_at.toISOString(),
    duration_value: w.duration_value,
    duration_unit: w.duration_unit,
    due_at: w.due_at.toISOString(),
    extended_bd_total: w.extended_bd_total,
    extension_count: w.extension_count,
    blocks_client: w.blocks_client,
    client_waiting_since: w.client_waiting_since ? w.client_waiting_since.toISOString() : null,
    paused_until: w.paused_until ? w.paused_until.toISOString() : null,
    switch_key: w.switch_key,
    terminal_action: w.terminal_action,
    fired_at: w.fired_at ? w.fired_at.toISOString() : null,
    sent_at: w.sent_at ? w.sent_at.toISOString() : null,
    fire_error: w.fire_error,
    fire_error_count: w.fire_error_count,
    nag_level: w.nag_level,
    created_by_automation: w.created_by_automation,
    resolved_at: w.resolved_at ? w.resolved_at.toISOString() : null,
    resolution: w.resolution,
    created_at: w.created_at.toISOString(),
    updated_at: w.updated_at.toISOString(),
  };
}
